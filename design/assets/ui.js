// Replace <i class="ic" data-i="name" data-s="20"> with an inline SVG whose stroke is the computed text color
function renderIcons() {
  document.querySelectorAll('i[data-i]').forEach(el => {
    const size = el.dataset.s || 20;
    const color = getComputedStyle(el).color;
    el.style.width = el.style.height = size + 'px';
    el.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" xmlns="http://www.w3.org/2000/svg">${ICONS[el.dataset.i] || ''}</svg>`;
  });
}

// Seat map generated from class + size (same rule as the analysis: buildSeatMap(class, size))
// <div class="bus" data-class="regular|first|business" data-size="large|medium" data-booked="1,2" data-selected="14"></div>
const LAYOUTS = { regular: [2, 2, true], first: [2, 1, false], business: [1, 1, false] };
function renderSeatMaps() {
  document.querySelectorAll('.bus[data-class]').forEach(el => {
    const [left, right, backMiddle] = LAYOUTS[el.dataset.class];
    const rows = el.dataset.size === 'medium' ? 9 : 11;
    const list = k => new Set((el.dataset[k] || '').split(',').filter(Boolean).map(Number));
    const booked = list('booked'), selected = list('selected');
    const seat = n => `<span class="seat ${selected.has(n) ? 'selected' : booked.has(n) ? 'booked' : ''}">${n}</span>`;
    let html = `<div class="bus-front"><span class="seat driver"><i class="ic" data-i="steering" data-s="18"></i></span><span class="door">الباب</span></div>`;
    let n = 1;
    for (let r = 1; r <= rows; r++) {
      const last = r === rows;
      let row = '<div class="bus-row">';
      for (let i = 0; i < left; i++) row += seat(n++);
      row += last && backMiddle ? seat(n++) : '<span class="aisle"></span>';
      for (let i = 0; i < right; i++) row += seat(n++);
      el.insertAdjacentHTML('beforeend', row + '</div>');
    }
    el.insertAdjacentHTML('afterbegin', html);
    el.dataset.capacity = n - 1;
  });
}

// #only=3 shows just the third frame (handy for screenshots and for importing one screen at a time)
function filterFrames() {
  if (location.hash.includes('shot')) document.body.classList.add('shot');
  const m = location.hash.match(/only=(\d+)/);
  if (!m) return;
  document.querySelectorAll('.frame').forEach((f, i) => { if (i + 1 !== Number(m[1])) f.remove(); });
}

document.addEventListener('DOMContentLoaded', () => { filterFrames(); renderSeatMaps(); renderIcons(); });
